<?php

namespace App\Http\Controllers\Admin;

use App\Http\Controllers\Controller;
use App\Models\Vendor;
use Illuminate\Http\Request;

class VendorController extends Controller
{
    /**
     * Vendor List
     */
    public function index()
    {
        $vendors = Vendor::with('user')
            ->latest()
            ->paginate(20);

        return view(
            'admin.vendors.index',
            compact('vendors')
        );
    }

    /**
     * Update Vendor
     */
    public function update(
        Request $request,
        $id
    ) {

        /*
        |--------------------------------------------------------------------------
        | Current Admin Role
        |--------------------------------------------------------------------------
        */

        $currentRole = strtolower(
            str_replace(
                [' ', '-'],
                '_',
                auth()->user()->role->role_name ?? ''
            )
        );

        /*
        |--------------------------------------------------------------------------
        | Permission
        |--------------------------------------------------------------------------
        */

        if (!in_array($currentRole, [
            'super_admin',
            'admin',
        ])) {
            abort(403);
        }

        /*
        |--------------------------------------------------------------------------
        | Find Vendor
        |--------------------------------------------------------------------------
        */

        $vendor = Vendor::with('user')
            ->findOrFail($id);

        /*
        |--------------------------------------------------------------------------
        | Validate
        |--------------------------------------------------------------------------
        */

        $validated = $request->validate([

            'business_name' => [
                'required',
                'string',
                'max:255',
            ],

            'phone' => [
                'nullable',
                'string',
                'max:30',
            ],

            'address' => [
                'nullable',
                'string',
                'max:500',
            ],

            'description' => [
                'nullable',
                'string',
            ],

            'commission_rate' => [
                'required',
                'numeric',
                'min:0',
                'max:100',
            ],

            'status' => [
                'required',
                'in:pending,approved,rejected',
            ],
        ]);

        /*
        |--------------------------------------------------------------------------
        | Update Vendor
        |--------------------------------------------------------------------------
        */

        $vendor->update([
            'business_name' =>
                $validated['business_name'],

            'phone' =>
                $validated['phone'] ?? null,

            'address' =>
                $validated['address'] ?? null,

            'description' =>
                $validated['description'] ?? null,

            'commission_rate' =>
                $validated['commission_rate'],

            'status' =>
                $validated['status'],
        ]);

        /*
        |--------------------------------------------------------------------------
        | Update User Status
        |--------------------------------------------------------------------------
        |
        | approved = 1
        | pending   = 0
        | rejected  = 0
        |
        |--------------------------------------------------------------------------
        */

        if ($vendor->user) {

            $vendor->user->update([
                'status' =>
                    $validated['status'] === 'approved'
                        ? 1
                        : 0,
            ]);
        }

        /*
        |--------------------------------------------------------------------------
        | Success
        |--------------------------------------------------------------------------
        */

        return back()->with(
            'success',
            'Vendor information updated successfully.'
        );
    }

    /**
     * Approve Vendor
     */
    public function approve($id)
    {
        /*
        |--------------------------------------------------------------------------
        | Current Admin Role
        |--------------------------------------------------------------------------
        */

        $currentRole = strtolower(
            str_replace(
                [' ', '-'],
                '_',
                auth()->user()->role->role_name ?? ''
            )
        );

        /*
        |--------------------------------------------------------------------------
        | Permission
        |--------------------------------------------------------------------------
        */

        if (!in_array($currentRole, [
            'super_admin',
            'admin',
        ])) {
            abort(403);
        }

        /*
        |--------------------------------------------------------------------------
        | Find Vendor
        |--------------------------------------------------------------------------
        */

        $vendor = Vendor::with('user')
            ->findOrFail($id);

        /*
        |--------------------------------------------------------------------------
        | Approve Vendor
        |--------------------------------------------------------------------------
        */

        $vendor->update([
            'status' => 'approved',
        ]);

        /*
        |--------------------------------------------------------------------------
        | Activate User
        |--------------------------------------------------------------------------
        */

        if ($vendor->user) {

            $vendor->user->update([
                'status' => 1,
            ]);
        }

        /*
        |--------------------------------------------------------------------------
        | Success
        |--------------------------------------------------------------------------
        */

        return back()->with(
            'success',
            'Vendor approved successfully.'
        );
    }

    /**
     * Reject Vendor
     */
    public function reject($id)
    {
        /*
        |--------------------------------------------------------------------------
        | Current Admin Role
        |--------------------------------------------------------------------------
        */

        $currentRole = strtolower(
            str_replace(
                [' ', '-'],
                '_',
                auth()->user()->role->role_name ?? ''
            )
        );

        /*
        |--------------------------------------------------------------------------
        | Permission
        |--------------------------------------------------------------------------
        */

        if (!in_array($currentRole, [
            'super_admin',
            'admin',
        ])) {
            abort(403);
        }

        /*
        |--------------------------------------------------------------------------
        | Find Vendor
        |--------------------------------------------------------------------------
        */

        $vendor = Vendor::with('user')
            ->findOrFail($id);

        /*
        |--------------------------------------------------------------------------
        | Reject Vendor
        |--------------------------------------------------------------------------
        */

        $vendor->update([
            'status' => 'rejected',
        ]);

        /*
        |--------------------------------------------------------------------------
        | Disable User
        |--------------------------------------------------------------------------
        */

        if ($vendor->user) {

            $vendor->user->update([
                'status' => 0,
            ]);
        }

        /*
        |--------------------------------------------------------------------------
        | Success
        |--------------------------------------------------------------------------
        */

        return back()->with(
            'success',
            'Vendor rejected successfully.'
        );
    }

    /**
     * Delete Vendor
     */
    public function destroy($id)
    {
        /*
        |--------------------------------------------------------------------------
        | Current Admin Role
        |--------------------------------------------------------------------------
        */

        $currentRole = strtolower(
            str_replace(
                [' ', '-'],
                '_',
                auth()->user()->role->role_name ?? ''
            )
        );

        /*
        |--------------------------------------------------------------------------
        | Permission
        |--------------------------------------------------------------------------
        */

        if (!in_array($currentRole, [
            'super_admin',
            'admin',
        ])) {
            abort(403);
        }

        /*
        |--------------------------------------------------------------------------
        | Find Vendor
        |--------------------------------------------------------------------------
        */

        $vendor = Vendor::with('user')
            ->findOrFail($id);

        /*
        |--------------------------------------------------------------------------
        | Delete
        |--------------------------------------------------------------------------
        */

        $vendor->delete();

        /*
        |--------------------------------------------------------------------------
        | Success
        |--------------------------------------------------------------------------
        */

        return back()->with(
            'success',
            'Vendor deleted successfully.'
        );
    }
}
